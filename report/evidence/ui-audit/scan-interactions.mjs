import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const dir='report/evidence/ui-audit';
mkdirSync(`${dir}/states`,{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1600,height:900},reducedMotion:'no-preference'});
const page=await context.newPage();
const checks=[];
try {
 await page.goto('http://127.0.0.1:3000/explore');
 await page.getByRole('button',{name:/Fuzhou shadow puppetry/}).waitFor();
 const world=page.locator('.atlas-world');
 const initial=await world.getAttribute('viewBox');
 await page.getByRole('combobox',{name:'Region',exact:true}).click();
 await page.getByRole('option',{name:'Dalian',exact:true}).click();
 await page.waitForTimeout(200);
 checks.push({id:'region-camera',before:initial,afterDropdown:await world.getAttribute('viewBox'),highlight:await page.locator('.atlas-district-selected').getAttribute('data-city-id')});
 await page.getByRole('button',{name:'Select Dalian',exact:true}).click();
 checks.at(-1).afterDirectory=await world.getAttribute('viewBox');
 await page.getByRole('button',{name:/Fuzhou shadow puppetry/}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('heading',{name:'Fuzhou shadow puppetry',exact:true}).waitFor();
 const cycle=[];
 for(let i=0;i<7;i++) {
  cycle.push(await page.evaluate(()=>({tag:document.activeElement.tagName,text:document.activeElement.textContent?.trim().slice(0,100)})));
  await page.keyboard.press('Tab');
 }
 checks.push({id:'source-summary-keyboard',cycle,hasSummary:await dialog.locator('summary').count()});
 await page.screenshot({path:`${dir}/states/published-exhibit-drawer-desktop.png`,fullPage:false});
 const rect=await dialog.boundingBox();
 await page.mouse.click(rect.x+8,rect.y+rect.height/2);
 await page.waitForTimeout(100);
 checks.push({id:'drawer-padding-dismissal',clicked:{x:rect.x+8,y:rect.y+rect.height/2},dialogStillOpen:await dialog.isVisible()});
 await page.goto('http://127.0.0.1:3000/dna');
 await page.getByRole('button',{name:'Edit interests'}).click();
 await page.getByRole('slider',{name:'Craft'}).focus();
 await page.keyboard.press('Home');
 await page.getByRole('slider',{name:'Food culture'}).focus();
 await page.keyboard.press('End');
 await page.screenshot({path:`${dir}/states/dna-edit-desktop.png`,fullPage:false});
 await page.goto('http://127.0.0.1:3000/guide');
 const input=page.getByRole('textbox',{name:'Ask the guide'});
 await input.fill('Question one'); await page.getByRole('button',{name:/Send/}).click();
 await page.waitForTimeout(700);
 await input.fill('Question two'); await page.getByRole('button',{name:/Send/}).click();
 await page.waitForTimeout(700);
 checks.push({id:'guide-history',questionOneVisible:await page.getByText('Question one',{exact:true}).count(),questionTwoVisible:await page.getByText('Question two',{exact:true}).count()});
 await page.goto('http://127.0.0.1:3000/journey');
 await page.getByRole('combobox',{name:'Time',exact:true}).click();
 await page.getByRole('option',{name:'5 minutes',exact:true}).click();
 checks.push({id:'journey-time-consistency',beforeGenerate:await page.locator('.panel-heading').textContent(),overflowNotice:await page.getByRole('status').allTextContents()});
 await page.getByRole('button',{name:'Move down screen'}).click();
 await page.goto('http://127.0.0.1:3000/guide');
 await page.goto('http://127.0.0.1:3000/journey');
 checks.push({id:'journey-navigation-reset',time:await page.getByRole('combobox',{name:'Time',exact:true}).textContent(),firstStop:await page.locator('.journey-stops li').first().textContent()});
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:3000/explore');
 await page.getByRole('button',{name:'Select Dalian',exact:true}).click();
 const atlas=page.getByRole('region',{name:'Interactive map of Liaoning'});
 await atlas.getByRole('button',{name:'Expand map',exact:true}).click();
 await page.screenshot({path:`${dir}/states/map-expanded-phone.png`,fullPage:false});
 checks.push({id:'map-expanded-semantics',role:await atlas.getAttribute('role'),ariaModal:await atlas.getAttribute('aria-modal'),focus:await page.evaluate(()=>document.activeElement.getAttribute('aria-label'))});
 await page.keyboard.press('Escape');
 await page.goto('http://127.0.0.1:3000/does-not-exist');
 await page.screenshot({path:`${dir}/states/not-found-phone.png`,fullPage:false});
 checks.push({id:'not-found',text:await page.locator('body').innerText()});
 writeFileSync(`${dir}/interactions.json`,JSON.stringify({checked_at:new Date().toISOString(),checks},null,2)+'\n');
 console.log(JSON.stringify(checks,null,2));
} finally { await browser.close(); }
